-- ATL Travels application schema for Neon Data API.
-- Managed Better Auth owns the neon_auth schema. This file contains only app tables.

CREATE TABLE IF NOT EXISTS public.profiles (
  id text PRIMARY KEY DEFAULT auth.user_id(),
  email text NOT NULL UNIQUE,
  full_name text,
  phone text,
  role text NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.destinations (
  id bigint PRIMARY KEY,
  name text NOT NULL,
  location text NOT NULL,
  description text NOT NULL DEFAULT '',
  price numeric(12, 2) NOT NULL DEFAULT 0 CHECK (price >= 0),
  rating text NOT NULL DEFAULT '5.0',
  reviews text NOT NULL DEFAULT '',
  image text NOT NULL DEFAULT '',
  media jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.flights (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  airline text NOT NULL,
  departure_city text NOT NULL DEFAULT 'ATL',
  arrival_city text NOT NULL,
  departure_date text,
  arrival_date text,
  price numeric(12, 2) NOT NULL DEFAULT 0 CHECK (price >= 0),
  available_seats integer NOT NULL DEFAULT 0 CHECK (available_seats >= 0),
  duration text NOT NULL DEFAULT '',
  stops text NOT NULL DEFAULT 'Non-stop',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.media (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id text NOT NULL DEFAULT auth.user_id(),
  file_name text NOT NULL,
  file_url text NOT NULL,
  storage_path text NOT NULL,
  file_type text NOT NULL CHECK (file_type IN ('photo', 'video')),
  bucket text NOT NULL DEFAULT 'media',
  title text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.bookings (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  reference text NOT NULL UNIQUE DEFAULT ('ATL-' || lpad(floor(random() * 9000 + 1000)::text, 4, '0')),
  user_id text NOT NULL DEFAULT auth.user_id(),
  item_type text NOT NULL CHECK (item_type IN ('flight', 'destination')),
  destination_id bigint,
  flight_id bigint,
  item_name text NOT NULL,
  unit_price numeric(12, 2) NOT NULL CHECK (unit_price >= 0),
  passengers integer NOT NULL CHECK (passengers BETWEEN 1 AND 20),
  total_price numeric(12, 2) NOT NULL CHECK (total_price = unit_price * passengers),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected', 'canceled')),
  payment_method text NOT NULL CHECK (payment_method IN ('cashapp', 'venmo', 'zelle', 'cryptocurrency', 'bank_transfer', 'paypal')),
  payment_instructions text NOT NULL DEFAULT '',
  payment_status text NOT NULL DEFAULT 'unpaid' CHECK (payment_status IN ('unpaid', 'pending', 'paid', 'failed')),
  payment_amount numeric(12, 2) CHECK (payment_amount IS NULL OR payment_amount >= 0),
  payment_reference text,
  payment_updated_at timestamptz,
  payment_updated_by text,
  full_name text NOT NULL,
  dob date,
  phone text NOT NULL DEFAULT '',
  passport text NOT NULL DEFAULT '',
  country text NOT NULL DEFAULT '',
  state text NOT NULL DEFAULT '',
  address text NOT NULL DEFAULT '',
  reason text NOT NULL DEFAULT '',
  emergency_name text NOT NULL DEFAULT '',
  emergency_phone text NOT NULL DEFAULT '',
  special_requests text NOT NULL DEFAULT '',
  destination text NOT NULL DEFAULT '',
  travel_date date NOT NULL DEFAULT CURRENT_DATE,
  travelers integer NOT NULL DEFAULT 1 CHECK (travelers BETWEEN 1 AND 20),
  notes text,
  reviewed_at timestamptz,
  reviewed_by text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (
    (item_type = 'destination' AND destination_id IS NOT NULL AND flight_id IS NULL)
    OR (item_type = 'flight' AND flight_id IS NOT NULL AND destination_id IS NULL)
  )
);

CREATE TABLE IF NOT EXISTS public.booking_receipts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  booking_id uuid NOT NULL,
  uploader_id text NOT NULL DEFAULT auth.user_id(),
  storage_path text NOT NULL,
  file_name text NOT NULL,
  mime_type text NOT NULL,
  file_size bigint NOT NULL CHECK (file_size > 0),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.chat_threads (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  booking_id uuid NOT NULL UNIQUE,
  user_id text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.chat_messages (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  thread_id uuid NOT NULL,
  sender_id text NOT NULL DEFAULT auth.user_id(),
  is_admin boolean NOT NULL DEFAULT false,
  body text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.trip_requests (
  id text PRIMARY KEY,
  user_id text NOT NULL DEFAULT auth.user_id(),
  destination text NOT NULL,
  from_city text NOT NULL,
  travelers integer NOT NULL CHECK (travelers BETWEEN 1 AND 20),
  start_date date NOT NULL,
  end_date date NOT NULL,
  budget text NOT NULL DEFAULT '',
  notes text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected')),
  quote numeric(12, 2) NOT NULL DEFAULT 0 CHECK (quote >= 0),
  admin_note text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (end_date >= start_date)
);

CREATE INDEX IF NOT EXISTS bookings_user_created_idx ON public.bookings (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS booking_receipts_booking_idx ON public.booking_receipts (booking_id, created_at DESC);
CREATE INDEX IF NOT EXISTS chat_threads_user_created_idx ON public.chat_threads (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS chat_messages_thread_created_idx ON public.chat_messages (thread_id, created_at ASC);
CREATE INDEX IF NOT EXISTS trip_requests_user_created_idx ON public.trip_requests (user_id, created_at DESC);

CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.profiles
    WHERE id = auth.user_id()
      AND role = 'admin'
  )
$$;

REVOKE ALL ON FUNCTION public.is_admin() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.is_admin() TO authenticated;

ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.destinations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.flights ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.media ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.bookings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.booking_receipts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.chat_threads ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.chat_messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.trip_requests ENABLE ROW LEVEL SECURITY;

CREATE POLICY profiles_read_self_or_admin ON public.profiles
  FOR SELECT TO authenticated
  USING (id = auth.user_id() OR public.is_admin());

CREATE POLICY profiles_insert_self ON public.profiles
  FOR INSERT TO authenticated
  WITH CHECK (id = auth.user_id() AND role = 'user');

CREATE POLICY profiles_update_self ON public.profiles
  FOR UPDATE TO authenticated
  USING (id = auth.user_id() AND role = 'user')
  WITH CHECK (id = auth.user_id() AND role = 'user');

CREATE POLICY profiles_admin_update ON public.profiles
  FOR UPDATE TO authenticated
  USING (public.is_admin())
  WITH CHECK (public.is_admin());

CREATE POLICY destinations_public_read ON public.destinations
  FOR SELECT TO anonymous, authenticated
  USING (true);

CREATE POLICY destinations_admin_write ON public.destinations
  FOR ALL TO authenticated
  USING (public.is_admin())
  WITH CHECK (public.is_admin());

CREATE POLICY flights_public_read ON public.flights
  FOR SELECT TO anonymous, authenticated
  USING (true);

CREATE POLICY flights_admin_write ON public.flights
  FOR ALL TO authenticated
  USING (public.is_admin())
  WITH CHECK (public.is_admin());

CREATE POLICY media_public_read ON public.media
  FOR SELECT TO anonymous, authenticated
  USING (true);

CREATE POLICY media_admin_write ON public.media
  FOR ALL TO authenticated
  USING (public.is_admin())
  WITH CHECK (public.is_admin());

CREATE POLICY bookings_read_self_or_admin ON public.bookings
  FOR SELECT TO authenticated
  USING (user_id = auth.user_id() OR public.is_admin());

CREATE POLICY bookings_insert_valid_own ON public.bookings
  FOR INSERT TO authenticated
  WITH CHECK (
    user_id = auth.user_id()
    AND status = 'pending'
    AND payment_status = 'unpaid'
    AND payment_instructions = ''
    AND payment_amount IS NULL
    AND payment_reference IS NULL
    AND payment_updated_at IS NULL
    AND payment_updated_by IS NULL
    AND total_price = unit_price * passengers
    AND (
      (item_type = 'destination' AND EXISTS (
        SELECT 1 FROM public.destinations d
        WHERE d.id = destination_id
          AND d.price = unit_price
          AND d.name = item_name
      ))
      OR (item_type = 'flight' AND EXISTS (
        SELECT 1 FROM public.flights f
        WHERE f.id = flight_id
          AND f.price = unit_price
          AND (f.airline || ' — ' || f.arrival_city) = item_name
      ))
    )
  );

CREATE POLICY bookings_admin_update ON public.bookings
  FOR UPDATE TO authenticated
  USING (public.is_admin())
  WITH CHECK (public.is_admin());

CREATE POLICY booking_receipts_read_self_or_admin ON public.booking_receipts
  FOR SELECT TO authenticated
  USING (
    uploader_id = auth.user_id()
    OR public.is_admin()
  );

CREATE POLICY booking_receipts_insert_for_own_booking ON public.booking_receipts
  FOR INSERT TO authenticated
  WITH CHECK (
    uploader_id = auth.user_id()
    AND EXISTS (
      SELECT 1 FROM public.bookings b
      WHERE b.id = booking_id AND b.user_id = auth.user_id()
    )
  );

CREATE POLICY chat_threads_read_self_or_admin ON public.chat_threads
  FOR SELECT TO authenticated
  USING (user_id = auth.user_id() OR public.is_admin());

CREATE POLICY chat_threads_admin_insert ON public.chat_threads
  FOR INSERT TO authenticated
  WITH CHECK (
    public.is_admin()
    AND EXISTS (
      SELECT 1 FROM public.bookings b
      WHERE b.id = public.chat_threads.booking_id
        AND b.user_id = public.chat_threads.user_id
    )
  );

CREATE POLICY chat_messages_read_thread_participants ON public.chat_messages
  FOR SELECT TO authenticated
  USING (
    public.is_admin()
    OR EXISTS (
      SELECT 1 FROM public.chat_threads t
      WHERE t.id = thread_id AND t.user_id = auth.user_id()
    )
  );

CREATE POLICY chat_messages_insert_thread_participants ON public.chat_messages
  FOR INSERT TO authenticated
  WITH CHECK (
    sender_id = auth.user_id()
    AND (
      (is_admin = false AND EXISTS (
        SELECT 1 FROM public.chat_threads t
        WHERE t.id = thread_id AND t.user_id = auth.user_id()
      ))
      OR (is_admin = true AND public.is_admin())
    )
  );

CREATE POLICY trip_requests_read_self_or_admin ON public.trip_requests
  FOR SELECT TO authenticated
  USING (user_id = auth.user_id() OR public.is_admin());

CREATE POLICY trip_requests_insert_own ON public.trip_requests
  FOR INSERT TO authenticated
  WITH CHECK (user_id = auth.user_id() AND status = 'pending' AND quote = 0 AND admin_note = '');

CREATE POLICY trip_requests_admin_update ON public.trip_requests
  FOR UPDATE TO authenticated
  USING (public.is_admin())
  WITH CHECK (public.is_admin());

GRANT USAGE ON SCHEMA public TO anonymous, authenticated;
